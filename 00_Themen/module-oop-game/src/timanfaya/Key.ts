/**
 * Enum of supported keyboard keys.
 * Values match KeyboardEvent.code — no translation needed in InputManager.
 */
export enum Key {
    Space = "Space",
    ArrowUp = "ArrowUp",
    ArrowDown = "ArrowDown",
    ArrowLeft = "ArrowLeft",
    ArrowRight = "ArrowRight",
    Enter = "Enter",
    Escape = "Escape",
    KeyW = "KeyW",
    KeyA = "KeyA",
    KeyS = "KeyS",
    KeyD = "KeyD",
}
